#!/usr/bin/env bash
# ═════════════════════════════════════════════════════════════════════
#  run-e2e.sh — Terminal-only E2E runner for epic-e2e-plan.md
#
#  USAGE:
#    ./agent-pipeline/bin/run-e2e.sh <EPIC_ID>
#
#  WHAT IT DOES:
#    1. Reads demo.e2e.framework + demo.e2e.{framework}.run_command from pipeline.yaml
#    2. Runs the test command (Protractor / Cypress / Playwright)
#    3. Parses JUnit XML output (all three frameworks support --reporter=junit)
#    4. Maps test names back to step numbers in epic-e2e-plan.md
#    5. Updates the Last Result + Screenshot columns in the plan
#    6. Prepends a row to the Run History table
#
#  COST: $0.00 — no LLM involved. Pure bash + yq + xmlstarlet.
#
#  PRE-REQUISITES:
#    - Specs must exist (generated by AC-E2E-Check in e2e_generate mode first)
#    - pipeline.yaml must have demo.e2e configured
#    - yq, xmlstarlet installed (brew install yq xmlstarlet)
# ═════════════════════════════════════════════════════════════════════

set -euo pipefail

EPIC_ID="${1:-}"
if [ -z "$EPIC_ID" ]; then
  echo "Usage: $0 <EPIC_ID>   e.g.  $0 PROJ-EPIC-100"
  exit 1
fi

PROJECT_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PIPELINE_YAML="${PROJECT_ROOT}/contexts/config/pipeline.yaml"
PLAN_FILE="${PROJECT_ROOT}/contexts/${EPIC_ID}/epic-e2e-plan.md"

# ── 1. Sanity checks ────────────────────────────────────────────
if [ ! -f "$PIPELINE_YAML" ]; then
  echo "⛔ pipeline.yaml not found at $PIPELINE_YAML"; exit 1
fi

if [ ! -f "$PLAN_FILE" ]; then
  echo "⛔ Plan not found: $PLAN_FILE"
  echo "   Run pipeline through Ship for at least one story first,"
  echo "   or use: AC-E2E-Check with Create epic plan $EPIC_ID"
  exit 1
fi

# Source shell init for build tools (if configured)
SHELL_INIT=$(yq '.demo.pre_verify.shell_init // ""' "$PIPELINE_YAML")
if [ -n "$SHELL_INIT" ] && [ "$SHELL_INIT" != "null" ]; then
  eval "$SHELL_INIT"
fi

# ── 2. Read framework config ────────────────────────────────────
FRAMEWORK=$(yq '.demo.e2e.framework' "$PIPELINE_YAML")
RUN_CMD=$(yq ".demo.e2e.${FRAMEWORK}.run_command" "$PIPELINE_YAML")
SPEC_DIR=$(yq ".demo.e2e.${FRAMEWORK}.spec_dir" "$PIPELINE_YAML")
SPEC_PATTERN=$(yq ".demo.e2e.${FRAMEWORK}.spec_pattern" "$PIPELINE_YAML" | sed "s/{TICKET_ID}/${EPIC_ID}/")

# Find all spec files related to this epic (matches any story in the epic).
# Project prefix is read from pipeline.yaml so this script is project-neutral.
PROJECT_KEY=$(yq '.jira.project_key // ""' "$PIPELINE_YAML")
if [ -z "$PROJECT_KEY" ] || [ "$PROJECT_KEY" = "null" ]; then
  echo "⛔ jira.project_key not set in pipeline.yaml — cannot filter spec files."
  exit 1
fi

SPECS=$(find "$SPEC_DIR" -name "*.spec.*" -o -name "*.cy.*" 2>/dev/null | grep -E "${PROJECT_KEY}" || true)
if [ -z "$SPECS" ]; then
  echo "⚠ No spec files found in $SPEC_DIR"
  echo "  Generate them first: Demo ${PROJECT_KEY}-XXXX  (with verify_mode: e2e_generate)"
  exit 1
fi

echo "→ Found $(echo "$SPECS" | wc -l) spec file(s) for $EPIC_ID"

# ── 3. Run the tests with JUnit reporter ────────────────────────
RUN_ID=$(date +%Y-%m-%d_%H-%M)
RESULTS_DIR="${PROJECT_ROOT}/contexts/${EPIC_ID}/test-results/${RUN_ID}"
mkdir -p "$RESULTS_DIR"

case "$FRAMEWORK" in
  protractor)
    # Protractor uses jasmine-reporters for JUnit XML
    export PROTRACTOR_JUNIT_DIR="$RESULTS_DIR"
    FULL_CMD="$RUN_CMD --output-dir=$RESULTS_DIR"
    ;;
  cypress)
    FULL_CMD="$RUN_CMD --reporter junit --reporter-options 'mochaFile=$RESULTS_DIR/results-[hash].xml'"
    ;;
  playwright)
    export PLAYWRIGHT_JUNIT_OUTPUT_NAME="$RESULTS_DIR/results.xml"
    FULL_CMD="$RUN_CMD --reporter=junit"
    ;;
esac

echo "→ Running: $FULL_CMD"
EXIT_CODE=0
eval "$FULL_CMD" || EXIT_CODE=$?

# ── 4. Parse JUnit XML results ──────────────────────────────────
JUNIT_FILES=$(find "$RESULTS_DIR" -name "*.xml")
if [ -z "$JUNIT_FILES" ]; then
  echo "⚠ No JUnit output produced — check framework config"
  exit 1
fi

TOTAL=0
PASSED=0
FAILED=0
SKIPPED=0
FAILURES=""

for f in $JUNIT_FILES; do
  # xmlstarlet extracts testcase names + statuses
  while IFS=$'\t' read -r name status err; do
    TOTAL=$((TOTAL + 1))
    case "$status" in
      pass) PASSED=$((PASSED + 1)) ;;
      fail) FAILED=$((FAILED + 1)); FAILURES="${FAILURES}${name}: ${err}\n" ;;
      skip) SKIPPED=$((SKIPPED + 1)) ;;
    esac
  done < <(xmlstarlet sel -t -m "//testcase" \
           -v "@name" -o $'\t' \
           -i "failure" -o "fail" -o $'\t' -v "failure/@message" -b \
           -i "skipped" -o "skip" -o $'\t' -b \
           -i "not(failure) and not(skipped)" -o "pass" -o $'\t' -b \
           -n "$f" 2>/dev/null || true)
done

echo "→ Results: $PASSED passed, $FAILED failed, $SKIPPED skipped (of $TOTAL)"

# ── 5. Update Last Result columns in plan ───────────────────────
# Test name convention expected from generated specs:
#   "ACn: {description}"  — e.g. "AC1: should show multi-select"
# We match on AC ID → update the row with that AC in Story column

TODAY=$(date +%Y-%m-%d)
PLAN_TMP="${PLAN_FILE}.tmp"
cp "$PLAN_FILE" "$PLAN_TMP"

for f in $JUNIT_FILES; do
  while IFS=$'\t' read -r name status; do
    # Extract AC ID from test name (e.g. "AC1:" → "AC1")
    AC_ID=$(echo "$name" | grep -oE '^AC[0-9]+(-[A-Z0-9]+)?' || true)
    [ -z "$AC_ID" ] && continue

    case "$status" in
      pass) MARK="✅ $TODAY" ;;
      fail) MARK="❌ $TODAY" ;;
      skip) MARK="⏭ $TODAY" ;;
    esac

    # Update rows where AC column matches — using awk for markdown table editing
    awk -v ac="$AC_ID" -v mark="$MARK" '
      /^\|/ && $0 ~ "\\| " ac " \\|" {
        # Replace the Last Result column (6th column in the table)
        n = split($0, cols, "|")
        cols[7] = " " mark " "
        result = ""
        for (i = 1; i <= n; i++) {
          result = result "|" cols[i]
        }
        print result
        next
      }
      { print }
    ' "$PLAN_TMP" > "${PLAN_TMP}.new" && mv "${PLAN_TMP}.new" "$PLAN_TMP"
  done < <(xmlstarlet sel -t -m "//testcase" \
           -v "@name" -o $'\t' \
           -i "failure" -o "fail" -b \
           -i "skipped" -o "skip" -b \
           -i "not(failure) and not(skipped)" -o "pass" -b \
           -n "$f" 2>/dev/null || true)
done

# ── 6. Prepend row to Run History ───────────────────────────────
RUN_ROW="| $TODAY | run-e2e.sh $EPIC_ID | $FRAMEWORK (headless) | $PASSED/$TOTAL | $FAILED fails |"

awk -v row="$RUN_ROW" '
  /^## Run History/ { print; found=1; next }
  found && /^\|------/ { print; print row; found=0; next }
  { print }
' "$PLAN_TMP" > "${PLAN_TMP}.new" && mv "${PLAN_TMP}.new" "$PLAN_TMP"

# ── 7. Update Coverage Summary "Last test run" column ───────────
sed -i.bak -E "s|(Last test run[^|]*\\| ).*(\\| [0-9]+ of)|\1$TODAY by run-e2e.sh \2|" "$PLAN_TMP"
rm -f "${PLAN_TMP}.bak"

mv "$PLAN_TMP" "$PLAN_FILE"

# ── 8. Report ───────────────────────────────────────────────────
echo ""
echo "═══════════════════════════════════════════════════════════════"
echo "  E2E run complete for $EPIC_ID"
echo "═══════════════════════════════════════════════════════════════"
echo "  Framework:    $FRAMEWORK"
echo "  Results:      $PASSED / $TOTAL passed, $FAILED failed, $SKIPPED skipped"
echo "  Plan updated: $PLAN_FILE"
echo "  Results dir:  $RESULTS_DIR"
echo "  LLM tokens:   0 (no AI used)"
echo ""
if [ "$FAILED" -gt 0 ]; then
  echo "  ⚠ $FAILED test(s) failed. For AI diagnosis of failures, run:"
  echo "    Demo epic $EPIC_ID --diagnose"
  echo ""
fi

exit $EXIT_CODE
